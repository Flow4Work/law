const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 page.on('pageerror',e=>console.log('PAGE_ERROR',e.message));
 page.on('console',m=>{if(m.type()==='error')console.log('BROWSER_ERROR',m.text().slice(0,300))});
 await page.goto('http://127.0.0.1:3700/',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.body.innerText.includes('GLM 5.3 Flash'),null,{timeout:15000});
 await page.getByRole('textbox',{name:'내 상황 입력'}).fill('퇴사 후 마지막 월급을 받지 못했어요. 회사에 문자로 요구했습니다.');
 await page.waitForFunction(()=>{const b=document.querySelector('button[aria-label="메시지 보내기"]');return b&&!b.disabled;},null,{timeout:12000});
 await page.getByRole('button',{name:'메시지 보내기'}).click();
 await page.locator('.intake-card').waitFor({timeout:15000});
 console.log('QUESTION_1',await page.locator('.intake-card h2').innerText());
 const first=await page.locator('.stage-card').count();
 console.log('ROUTES_INITIAL',first);
 await page.locator('.intake-options button').first().click();
 await page.locator('.intake-next').click();
 await page.getByText('2 / 3').waitFor({timeout:5000});
 console.log('QUESTION_2',await page.locator('.intake-card h2').innerText());
 await page.locator('.intake-options button').first().click();
 await page.locator('.intake-next').click();
 await page.getByText('3 / 3').waitFor({timeout:5000});
 console.log('QUESTION_3',await page.locator('.intake-card h2').innerText());
 console.log('ROUTES_AFTER_TWO',await page.locator('.stage-card').count());
 await page.screenshot({path:'scripts/intake-ui-check.png',fullPage:true});
 await page.locator('.intake-options button').first().click();
 await page.locator('.intake-next').click();
 await page.getByText('추가 질문에 대한 답변:',{exact:false}).first().waitFor({timeout:5000});
 console.log('FINAL_REQUEST_TRIGGERED',await page.locator('.analysis-progress').count());
 await page.waitForFunction(()=>{const v=JSON.parse(localStorage.getItem('ai-legal-roadmap-cases-v1')||'[]');return v.some(x=>x.messages?.some(m=>m.role==='assistant'&&!m.error)&&!x.intake);},null,{timeout:110000}).catch(()=>console.log('FINAL_PENDING_OR_FAILED'));
 const record=await page.evaluate(()=>JSON.parse(localStorage.getItem('ai-legal-roadmap-cases-v1')||'[]').at(-1));
 console.log('RESULT',JSON.stringify({messages:record?.messages?.map(m=>({role:m.role,error:m.error,content:m.content.slice(0,220)})),intake:Boolean(record?.intake),nodes:record?.nodes?.length}).slice(0,1400));
 await browser.close();
})().catch(e=>{console.error('TEST_FAILED',e.stack);process.exitCode=1});